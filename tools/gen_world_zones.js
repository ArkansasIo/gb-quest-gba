#!/usr/bin/env node
/**
 * Generates the world data files: `src/world_zones.c`.
 *
 * The world is a hand-authored zone grid: 9x8 = 72 zones, one per map chunk.
 * - Each zone has a biome (forest, plains, desert, swamp, foothills, coastal,
 *   snowfield, volcanic, underground) and a sub-biome for terrain variety.
 * - Border zones have exit squares leading to neighboring zones.
 * - Town zones (every 3rd), hub zones (every 9th), and the tower entrance
 *   zone are flagged.
 * - The tower has 100 floors, generated as data. Floors 1..100.
 * - World routes (18) and trails (16) connect zones.
 */

const fs = require('fs');

const WORLD_ZONE_COUNT = 72;
const WORLD_ZONE_COLS = 9;
const WORLD_ZONE_ROWS = 8;
const WORLD_ZONE_MAP_W = 8;
const WORLD_ZONE_MAP_H = 8;
const WORLD_BIOME_COUNT = 9;
const WORLD_TOWER_MAX_FLOOR = 100;
const WORLD_ROUTE_COUNT = 18;
const WORLD_TRAIL_COUNT = 16;
const WORLD_DATA_BANK = 18;
const TOWER_ENTRANCE_ZONE = 31;

// Tile ids used for zone terrain (from res/tiles/dungeon.bin; 6-bit ids).
const BIOME_TILES = [0, 1, 2, 3, 4, 5, 6, 7, 8];

// Flags (match WorldZoneFlag in src/world.h).
const ZONE_FLAG_TOWN = 1;
const ZONE_FLAG_HUB = 2;
const ZONE_FLAG_UNDERGROUND = 4;
const ZONE_FLAG_TOWER_ENTRANCE = 8;

function zoneIdAt(col, row) {
  if (col < 0 || col >= WORLD_ZONE_COLS || row < 0 || row >= WORLD_ZONE_ROWS)
    return -1;
  return row * WORLD_ZONE_COLS + col;
}

function biomeOf(id) { return id % WORLD_BIOME_COUNT; }
function subBiomeOf(id) { return (id * 7 + 13) % 3; }

function zoneFlags(id) {
  let flags = 0;
  if (id % 3 === 0) flags |= ZONE_FLAG_TOWN;
  if (id % 9 === 0) flags |= ZONE_FLAG_HUB;
  if (biomeOf(id) === WORLD_BIOME_COUNT - 1) flags |= ZONE_FLAG_UNDERGROUND;
  if (id === TOWER_ENTRANCE_ZONE) flags |= ZONE_FLAG_TOWER_ENTRANCE;
  return flags;
}

function zoneMapData(id, biome, sub) {
  const data = [];
  for (let y = 0; y < WORLD_ZONE_MAP_H; y++) {
    for (let x = 0; x < WORLD_ZONE_MAP_W; x++) {
      const base = BIOME_TILES[biome];
      let t = base;
      if ((x + y * 3 + id + sub) % 2 === 0) t = base + 1;
      if ((x + y + id * 2 + sub) % 5 === 0) t = base + 2;
      data.push(t);
    }
  }
  return data;
}

function zoneExits(id) {
  const col = id % WORLD_ZONE_COLS;
  const row = Math.floor(id / WORLD_ZONE_COLS);
  const exits = [];
  const add = (c, r, heading, toFloor, toCol, toRow) => {
    exits.push({ map_id: id, col: c, row: r, to_map: 0, to_col: toCol, to_row: toRow, heading, exit_type: 0, to_floor: toFloor });
  };
  const nbr = (c, r) => zoneIdAt(c, r);
  if (nbr(col + 1, row) >= 0) add(7, 4, 'RIGHT', `&world_zone_banks[${nbr(col + 1, row)}]`, 0, 4);
  if (nbr(col - 1, row) >= 0) add(0, 4, 'LEFT', `&world_zone_banks[${nbr(col - 1, row)}]`, 7, 4);
  if (nbr(col, row + 1) >= 0) add(4, 7, 'DOWN', `&world_zone_banks[${nbr(col, row + 1)}]`, 4, 0);
  if (nbr(col, row - 1) >= 0) add(4, 0, 'UP', `&world_zone_banks[${nbr(col, row - 1)}]`, 4, 7);
  if (id === TOWER_ENTRANCE_ZONE) {
    exits.push({ map_id: id, col: 2, row: 1, to_map: 0, to_col: 2, to_row: 1, heading: 'DOWN', exit_type: 0, to_floor: '&tower_floor_banks[1]' });
  }
  exits.push({ map_id: 0xFF });
  return exits;
}

function towerFloorMapData(floor) {
  const data = [];
  for (let y = 0; y < WORLD_ZONE_MAP_H; y++) {
    for (let x = 0; x < WORLD_ZONE_MAP_W; x++) {
      const base = BIOME_TILES[WORLD_BIOME_COUNT - 1]; // underground
      data.push(base + ((x + y + floor) % 3));
    }
  }
  return data;
}

function towerFloorExits(floor) {
  const exits = [];
  let upTo;
  if (floor === 1) upTo = `&world_zone_banks[${TOWER_ENTRANCE_ZONE}]`;
  else upTo = `&tower_floor_banks[${floor - 1}]`;
  exits.push({ map_id: 100 + floor, col: 2, row: 1, to_map: 0, to_col: 2, to_row: 1, heading: 'UP', exit_type: 0, to_floor: upTo });
  if (floor < WORLD_TOWER_MAX_FLOOR) {
    exits.push({ map_id: 100 + floor, col: 4, row: 6, to_map: 0, to_col: 4, to_row: 7, heading: 'DOWN', exit_type: 0, to_floor: `&tower_floor_banks[${floor + 1}]` });
  }
  exits.push({ map_id: 0xFF });
  return exits;
}

const out = [];
const emit = (s) => out.push(s);

emit('#pragma bank ' + WORLD_DATA_BANK);
emit('');
emit('/*');
emit(' * world_zones.c - Generated world data (72 zones, 9x8 grid).');
emit(' * Generated by tools/gen_world_zones.js');
emit(' */');
emit('');
emit('#include "world.h"');
emit('');

for (let id = 0; id < WORLD_ZONE_COUNT; id++) {
  const biome = biomeOf(id);
  const sub = subBiomeOf(id);
  const flags = zoneFlags(id);
  const mapData = zoneMapData(id, biome, sub);
  const exits = zoneExits(id);

  emit(`/* Zone ${id} (biome ${biome}, sub-biome ${sub}, flags ${flags}) */`);
  emit(`static const uint8_t z${id}_map_data[WORLD_ZONE_MAP_BYTES] = { ${mapData.join(', ')} };`);
  emit(`static const Map z${id}_map = { ${id}, WORLD_DATA_BANK, z${id}_map_data, WORLD_ZONE_MAP_W, WORLD_ZONE_MAP_H };`);
  emit(`static const Exit z${id}_exits[] = {`);
  for (const e of exits) {
    if (e.map_id === 0xFF) { emit('  { 0xFF },'); continue; }
    if (e.to_floor) {
      emit(`  { ${e.map_id}, ${e.col}, ${e.row}, ${e.to_map}, ${e.to_col}, ${e.to_row}, ${e.heading}, EXIT_DOOR, (FloorBank *)${e.to_floor} },`);
    } else {
      emit(`  { ${e.map_id}, ${e.col}, ${e.row}, ${e.to_map}, ${e.to_col}, ${e.to_row}, ${e.heading}, EXIT_DOOR, NULL },`);
    }
  }
  emit('};');
  emit(`static const Sign z${id}_signs[] = { { 0xFF } };`);
  emit(`static const Chest z${id}_chests[] = { { 0xFF } };`);
  emit(`static const Lever z${id}_levers[] = { { 0xFF } };`);
  emit(`static const Door z${id}_doors[] = { { 0xFF } };`);
  emit(`static const Sconce z${id}_sconces[] = { { 0xFF } };`);
  emit(`static const NPC z${id}_npcs[] = { { 0xFF } };`);
  emit(`static const Floor z${id}_floor = { ${id}, 4, 4, NULL, &z${id}_map, z${id}_exits, z${id}_chests, z${id}_signs, z${id}_levers, z${id}_doors, z${id}_sconces, z${id}_npcs, NULL, NULL, NULL, NULL, NULL, NULL };`);
  emit('');
}

emit('const WorldZone world_zones[WORLD_ZONE_COUNT] = {');
for (let id = 0; id < WORLD_ZONE_COUNT; id++) {
  emit(`  { ${id}, ${biomeOf(id)}, ${subBiomeOf(id)}, ${zoneFlags(id)}, (Floor *)&z${id}_floor },`);
}
emit('};');
emit('');

emit('const FloorBank world_zone_banks[WORLD_ZONE_COUNT] = {');
for (let id = 0; id < WORLD_ZONE_COUNT; id++) {
  emit(`  { WORLD_DATA_BANK, world_zones[${id}].floor },`);
}
emit('};');
emit('');

for (let n = 1; n <= WORLD_TOWER_MAX_FLOOR; n++) {
  const mapData = towerFloorMapData(n);
  const exits = towerFloorExits(n);
  emit(`/* Tower floor ${n} */`);
  emit(`static const uint8_t zt${n}_map_data[WORLD_ZONE_MAP_BYTES] = { ${mapData.join(', ')} };`);
  emit(`static const Map zt${n}_map = { ${100 + n}, WORLD_DATA_BANK, zt${n}_map_data, WORLD_ZONE_MAP_W, WORLD_ZONE_MAP_H };`);
  emit(`static const Exit zt${n}_exits[] = {`);
  for (const e of exits) {
    if (e.map_id === 0xFF) { emit('  { 0xFF },'); continue; }
    emit(`  { ${e.map_id}, ${e.col}, ${e.row}, ${e.to_map}, ${e.to_col}, ${e.to_row}, ${e.heading}, EXIT_DOOR, (FloorBank *)${e.to_floor} },`);
  }
  emit('};');
  emit(`static const Sign zt${n}_signs[] = { { 0xFF } };`);
  emit(`static const Chest zt${n}_chests[] = { { 0xFF } };`);
  emit(`static const Lever zt${n}_levers[] = { { 0xFF } };`);
  emit(`static const Door zt${n}_doors[] = { { 0xFF } };`);
  emit(`static const Sconce zt${n}_sconces[] = { { 0xFF } };`);
  emit(`static const NPC zt${n}_npcs[] = { { 0xFF } };`);
  emit(`static const Floor zt${n}_floor = { ${100 + n}, 3, 3, NULL, &zt${n}_map, zt${n}_exits, zt${n}_chests, zt${n}_signs, zt${n}_levers, zt${n}_doors, zt${n}_sconces, zt${n}_npcs, NULL, NULL, NULL, NULL, NULL, NULL };`);
  emit('');
}

emit('const FloorBank tower_floor_banks[WORLD_TOWER_MAX_FLOOR + 1] = {');
emit('  { 0, NULL },');
for (let n = 1; n <= WORLD_TOWER_MAX_FLOOR; n++) {
  emit(`  { WORLD_DATA_BANK, (Floor *)&zt${n}_floor },`);
}
emit('};');
emit('');

// Routes: pairs of towns (every 3rd zone). Trails: pairs of adjacent zones.
const townIds = [];
for (let id = 0; id < WORLD_ZONE_COUNT; id++) if (id % 3 === 0) townIds.push(id);
emit('WorldRoute world_routes[WORLD_ROUTE_COUNT] = {');
for (let k = 0; k < WORLD_ROUTE_COUNT; k++) {
  const from = townIds[k % townIds.length];
  const to = townIds[(k * 5 + 3) % townIds.length];
  if (from === to) continue;
  emit(`  { ${from}, ${to}, 0 },`);
}
emit('};');
emit('');

emit('WorldRoute world_trails[WORLD_TRAIL_COUNT] = {');
for (let k = 0; k < WORLD_TRAIL_COUNT; k++) {
  emit(`  { ${k}, ${k + 1}, 1 },`);
}
emit('};');
fs.writeFileSync(__dirname + '/../src/world_zones.c', out.join('\n'));
console.log('world_zones.c generated');
console.log(`routes: ${townIds.length} towns; trails: ${WORLD_TRAIL_COUNT}`);
